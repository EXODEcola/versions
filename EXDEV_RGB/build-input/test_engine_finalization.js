'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const src=process.argv[2]; if(!src)throw Error('Source directory required');
const installer=fs.readFileSync(path.resolve(src,'..','Installer','installer-ui.ps1'),'utf8');
const start=installer.indexOf('function Finalize-Install([string]$Root) {');
const end=installer.indexOf('function Remove-Installation([string]$Root)',start);
assert(start>=0&&end>start,'Finalizer not found');
const finalizer=installer.slice(start,end);
assert(!finalizer.includes('  Stop-EXDEV'),'Finalization must never terminate resident native engine');
assert(finalizer.includes("Stop-Process -Name 'EXDEV RGB'"),'Only UI needs to close before final EXE replacement');
assert(finalizer.includes('Ensure-EXDEVNativeAfterInstall $Root'),'Installer must verify engine after update');
const helper=installer.slice(installer.indexOf('function Test-EXDEVNativePort'),start);
assert(helper.includes("BeginConnect('127.0.0.1',47651"),'Expected fixed loopback native port');
assert(helper.includes("Get-ScheduledTask -TaskName 'EXDEV RGB Native Engine'"),'Must inspect existing task');
assert(helper.includes('Start-ScheduledTask -TaskName'),'Must start existing task, not create unsafe service');
assert(helper.includes('$actual -ine $expected'),'Must check task executable before relaunch');
assert(helper.includes('WARN: Native Engine did not start'),'Must report persistent failure');
const ui=installer.slice(installer.indexOf('$InstallButton.Add_Click({'));
assert(ui.includes("if($script:NativeEngineWarning)"),'Must show hardware warning to user');
assert(installer.includes('Save-VerifiedRollback $script:OldRoot $target'),'Must retain rollback snapshot');
console.log('PASS: no post-install daemon kill, bounded engine health/restart, task path verified, warning and rollback retained.');
